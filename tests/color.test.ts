import { test } from "node:test";
import assert from "node:assert/strict";
import { DEFAULT_CONFIG } from "@design-axioms/color";
import { colorStylesheet } from "../scripts/build.ts";

const css = colorStylesheet();
const defines = (selector: string) =>
  new RegExp(`(?:^|[\\s,}])${selector.replace(/[.:-]/g, "\\$&")}\\s*\\{`).test(
    css,
  );

test("the stylesheet is for an ordinary document, not a shadow root", () => {
  assert.ok(defines(":root"));
  assert.ok(!css.includes(":host"), "no shadow-root selector");
  assert.ok(!css.includes("-simulate"), "no demo simulation classes");
});

test("atmosphere classes are generated for every key color", () => {
  // The generator leaves these out unless it is handed the key colors.
  const names = Object.keys(DEFAULT_CONFIG.keyColors ?? {});
  assert.ok(names.includes("brand") && names.includes("accent"));
  for (const name of names) {
    assert.ok(defines(`.hue-${name}`), `.hue-${name}`);
    assert.ok(css.includes(`--axm-key-${name}-hue:`), `${name} hue`);
  }
});

test("the surfaces, text grades and border tiers the page composes exist", () => {
  for (const selector of [
    ".surface-page",
    ".surface-workspace",
    ".surface-card",
    ".surface-action",
    ".text-high",
    ".text-strong",
    ".text-subtle",
    ".text-subtlest",
    ".text-link",
    ".border-decorative",
    ".border-interactive",
    ".border-critical",
  ])
    assert.ok(defines(selector), selector);
});

test("hover and active states belong to the actions inside the card", () => {
  for (const state of ["hover", "active"]) {
    assert.ok(!defines(`.surface-card:${state}`));
    assert.ok(defines(`.surface-action:${state}`));
  }
});

test("mode, contrast and forced colors are answered in CSS", () => {
  assert.ok(css.includes("light-dark("));
  assert.ok(css.includes("@media (prefers-contrast: more)"));
  assert.ok(css.includes("@media (forced-colors: active)"));
});

test("the stylesheet names the package and revision it came from", () => {
  assert.match(
    css.split("\n")[0]!,
    /^\/\* Generated by @design-axioms\/color \d+\.\d+\.\d+ \(MIT\), revision [0-9a-f]{40}\./,
  );
  assert.equal(colorStylesheet(), css, "generation is deterministic");
});
