/**
 * Builds the site into `dist/`.
 *
 * - `public/` is authored and copied as it is.
 * - `assets/color.css` is Axiomatic Color's own stylesheet, generated here
 *   from the vendored package. The site chooses semantic surfaces.
 * - `assets/site.js` and `assets/site.css` are bundled from `src/`, which
 *   imports the vendored Layout files directly.
 *
 *   node scripts/build.ts
 *
 * `watchSite` keeps `dist/` current for the preview server.
 */
import fs from "node:fs";
import path from "node:path";
import { DEFAULT_CONFIG, generateCSS, solve } from "@design-axioms/color";
import { context, type BuildOptions } from "esbuild";
import type { Provenance } from "./vendor.ts";

const root = path.resolve(import.meta.dirname, "..");
const publicDirectory = path.join(root, "public");
export const outputDirectory = path.join(root, "dist");
const assets = path.join(outputDirectory, "assets");

function provenance(name: string): Provenance {
  return JSON.parse(
    fs.readFileSync(path.join(root, "vendor", name, "provenance.json"), "utf8"),
  ) as Provenance;
}

/**
 * The site's Axiomatic Color system as CSS for an ordinary document: the
 * surface, text, border and hue classes, with `light-dark()` values that
 * follow `color-scheme` on the root.
 *
 * `keyColors` is passed separately because the generator emits the
 * `.hue-*` classes only when it is given them.
 */
export function colorStylesheet(): string {
  const { artifact, revision, license } = provenance("design-axioms-color");
  if (!artifact) throw new Error("vendor/design-axioms-color has no artifact");
  // The card contains actions. Only the actions have hover and active states.
  const { surfaces } = DEFAULT_CONFIG;
  const css = generateCSS(
    solve({
      ...DEFAULT_CONFIG,
      surfaces: { ...surfaces, page: { ...surfaces.page, card: 2 } },
    }),
    {
      ...DEFAULT_CONFIG.options,
      selector: ":root",
      ...(DEFAULT_CONFIG.keyColors && { keyColors: DEFAULT_CONFIG.keyColors }),
    },
  );
  return `/* Generated by ${artifact.package} ${artifact.version} (${license}), revision ${revision}. Do not edit. */\n${css}\n`;
}

function bundleOptions(): BuildOptions {
  const layout = provenance("axiomatic-layout");
  const note = `/* Includes Axiomatic Layout, ${layout.repository} at ${layout.revision}. */`;
  return {
    absWorkingDir: root,
    entryPoints: ["src/site.ts", "src/site.css"],
    outdir: assets,
    bundle: true,
    format: "esm",
    platform: "browser",
    // A JavaScript target only: CSS is passed through as authored.
    target: "es2024",
    minify: true,
    sourcemap: "linked",
    banner: { js: note, css: note },
    logLevel: "warning",
  };
}

function copyPublic() {
  fs.cpSync(publicDirectory, outputDirectory, { recursive: true });
}

/** `dist/` without the bundles: the authored files and Color's stylesheet. */
function prepare() {
  fs.rmSync(outputDirectory, { recursive: true, force: true });
  copyPublic();
  fs.mkdirSync(assets, { recursive: true });
  fs.writeFileSync(path.join(assets, "color.css"), colorStylesheet());
}

export async function buildSite() {
  prepare();
  const bundler = await context(bundleOptions());
  try {
    await bundler.rebuild();
  } finally {
    await bundler.dispose();
  }
}

/** Builds, then rebuilds when `src/`, the vendored Layout files or
 * `public/` change. A failed rebuild is reported and the watch continues. */
export async function watchSite(): Promise<{ stop(): Promise<void> }> {
  prepare();
  const bundler = await context({ ...bundleOptions(), logLevel: "info" });
  await bundler.watch();
  const watcher = fs.watch(publicDirectory, { recursive: true }, () => {
    try {
      copyPublic();
    } catch (error) {
      console.error(error);
    }
  });
  return {
    async stop() {
      watcher.close();
      await bundler.dispose();
    },
  };
}

if (import.meta.main) {
  await buildSite();
  console.log(`Built ${path.relative(root, outputDirectory)}/.`);
}
